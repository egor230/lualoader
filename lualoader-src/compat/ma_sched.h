// ma_sched.h — кооперативный планировщик Lua-скриптов (23.10.2026, ИГРОВОЙ ПОТОК).
//
// ЗАЧЕМ. До этой правки плагин поднимал ОТДЕЛЬНЫЙ OS-поток на КАЖДЫЙ .lua (а затем —
// один фоновый поток-планировщик) и каждый wait(ms) спал этим потоком (sleep_for).
// Поток ПОРТРЕБНИК лез в игровые структуры (CPools/CWorld/CMessages/стриминг)
// параллельно игровому циклу → гонки → вылеты «в чужом месте» (шрифт, msvcrt,
// освобождённая память при загрузке сохранения).
//
// КАК ТЕПЕРЬ. ВСЕ состояния Lua прокачивает ИГРОВОЙ поток: ma_sched_frame()
// вызывается из Events::gameProcessEvent (plugin.cpp). Никакого собственного
// OS-потока и thread_local:
//   * каждый скрипт — корутина (lua_resume), а не OS-поток;
//   * wait(ms) -> ma_sched_park() + lua_yield: скрипт ЗАСЫПАЕТ РОВНО на ms,
//     остальные скрипты и игра продолжают работать;
//   * бесконечный цикл без wait() вытесняется count-хуком (слайс 2 мс на скрипт,
//     проход кадра 12 мс) — один скрипт не может заморозить остальные;
//   * число скриптов не ограничено: реестр — динамический массив;
//   * все обращения к игровой памяти — на игровом потоке → гонок с движком нет
//     по определению.
//
// TEARDOWN (загрузка сохранения / Ctrl-reload) — двухфазный, тоже на игровом
// потоке: phase1 помечает состояния на завершение (_ma_terminate), phase2 каждый
// кадр «убивает» живые (wait()/хук шлют SCRIPT_STOPPED_BY_CPP), затем
// onScriptTerminate + destroy + снятие из реестров.
//
// Правила файла (как и во всех compat/*): НИ ОДНОГО глобального объекта с
// нетривиальным конструктором и НИ ОДНОГО thread_local — иначе в Wine игра не
// стартует (RtlpWaitForCriticalSection "... blocked by 0000") / BUILD-GATE в
// build.sh ловит регресс. Всё состояние — function-local static / POD.
//
// Потокобезопасность: ма_sched_scan/request_teardown/request_pause — атомарные
// флаги (можно ставить из любого потока). Всё остальное — ТОЛЬКО игровой поток
// (ма_sched_frame / ma_sched_park / ma_sched_hook / ma_sched_spawn).

#ifndef LUALOADER_MA_SCHED_H
#define LUALOADER_MA_SCHED_H

#include <lua.hpp>
#include <cstdint>

// Один кадр планировщика. Вызывается из Events::gameProcessEvent (игровой поток),
// после ma_tasks_frame(). Всё, что планировщику нужно сделать в кадре: сюда.
void ma_sched_frame();

// Запросить (пере)сканирование lualoader/*.lua. Потокобезопасно (флаг).
// Если скрипты уже загружены и teardown не было — запрос игнорируется.
void ma_sched_scan();

// wait(): припарковать текущий скрипт на ms. true -> вызывающий обязан сделать
// lua_yield(L, 0). false -> состояние не принадлежит планировщику (старый путь:
// вызывающий сам спит).
bool ma_sched_park(lua_State* L, int ms);

// count-хук планировщика (внутренний; ставится на каждую корутину).
void ma_sched_hook(lua_State* L, lua_Debug* ar);

// Полная разборка всех состояний (и, если restart, повторный скан).
// Потокобезопасно; сама разборка выполняется игровым потоком в ma_sched_frame().
void ma_sched_request_teardown(bool restart);

// Пауза/возобновление всех скриптов (обратимо): скрипты замирают на своём
// yield-пункте, ничего не закрывается.
void ma_sched_request_pause(bool paused);

// create_newthread(): зарегистрировать ещё один экземпляр скрипта (те же имя файла,
// другие аргументы main). Вызывается из Lua (игровой поток). parent — состояние,
// из которого вызвали; firstArg — индекс первого аргумента в стеке parent.
// Возвращает true, если экземпляр принят.
bool ma_sched_spawn(lua_State* parent, int firstArg);

// Сколько скриптов сейчас в реестре (атомарно, для heartbeat/логов).
int ma_sched_count();

// Монотонное время планировщика, мс.
uint64_t ma_sched_now_ms();

// Текущая корутина, если мы СЕЙЧАС внутри lua_resume (внутри биндинга), иначе
// nullptr. Для событийных ожиданий с парковкой (ma_stream_wait и пр.).
lua_State* ma_sched_current_L();

// Сколько реального времени (мс) занял ПРОШЕДШИЙ проход планировщика в кадре
// (метрика heartbeat: большой постоянный номер = скрипты едят игровой кадр).
unsigned ma_sched_last_pass_ms();

#endif // LUALOADER_MA_SCHED_H
